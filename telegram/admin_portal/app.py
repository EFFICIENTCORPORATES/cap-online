@app.route("/bots")
@auth.role_required("admin")
def bots_status():
    conn = get_conn()
    bots = manage_bots.load_bots()
    heartbeats = analytics.fetch_heartbeats(conn)
    rows = []
    for b in bots:
        bot_id = b["bot_id"]
        proc = manage_bots.is_running(bot_id, manage_bots.resolve_script_path(b))
        hb = heartbeats.get(bot_id)
        rows.append({
            "bot_id": bot_id,
            "kind": b["kind"],
            "display_name": b["display_name"],
            "config_status": b.get("status", "unknown"),
            "running": bool(proc),
            "pid": proc.pid if proc else None,
            "heartbeat_age": int(hb["age_seconds"]) if hb else None,
            "online": bool(hb and hb["online"]),
            "has_log": (manage_bots.LOG_DIR / f"{bot_id}.log").exists(),
        })
    return render_template("bots.html", rows=rows)


@app.route("/bots/<bot_id>/restart", methods=["POST"])
@auth.role_required("admin")
def bots_restart(bot_id):
    bots_by_id = {b["bot_id"]: b for b in manage_bots.load_bots()}
    bot = bots_by_id.get(bot_id)
    conn = get_conn()
    if not bot:
        flash(f"Unknown bot_id '{bot_id}'.", "error")
        audit.log_action(conn, auth.current_user(), "bot_restart", bot_id, "failed: unknown bot_id")
        return redirect(url_for("bots_status"))

    try:
        manage_bots.restart_bot(bot)
        flash(f"Restarted {bot['display_name']} ({bot_id}).", "success")
        audit.log_action(conn, auth.current_user(), "bot_restart", bot_id, "ok")
    except Exception as e:
        flash(f"Restart failed for {bot_id}: {e}", "error")
        audit.log_action(conn, auth.current_user(), "bot_restart", bot_id, f"failed: {e}")
    return redirect(url_for("bots_status"))


@app.route("/bots/<bot_id>/logs")
@auth.role_required("admin")
def bots_logs(bot_id):
    bots_by_id = {b["bot_id"]: b for b in manage_bots.load_bots()}
    bot = bots_by_id.get(bot_id)
    if not bot:
        return "Unknown bot_id.", 404

    log_path = manage_bots.LOG_DIR / f"{bot_id}.log"
    tail_n = request.args.get("lines", default=300, type=int)
    if log_path.exists():
        with open(log_path, encoding="utf-8", errors="replace") as f:
            all_lines = f.readlines()
        log_text = "".join(all_lines[-tail_n:])
        total_lines = len(all_lines)
    else:
        log_text = "(no log file yet -- this bot may never have been started)"
        total_lines = 0

    return render_template(
        "bot_logs.html", bot=bot, log_text=log_text, log_path=str(log_path),
        tail_n=tail_n, total_lines=total_lines,
    )


