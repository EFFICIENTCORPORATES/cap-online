@app.route("/analytics/students/send-report", methods=["POST"])
@auth.role_required("admin")
def analytics_students_send_report():
    """Sends each selected student their OWN existing performance report
    (the same PDF generate_student_report.py already produces), ONLY to a
    student's already echo-confirmed email on file (Pranav's confirmed
    choice, 2026-08-11 -- never guessed/typed in for them here). A student
    with no confirmed email is reported as skipped, never silently
    dropped. Sent from the admin portal's own dedicated address
    ('reports@1lavya.com', bots.json's 1lavya-admin-portal entry) -- an
    honest label, not impersonating whichever bot the student happens to
    use, since this send is admin-triggered, not bot-triggered."""
    conn = get_conn()
    selected = request.form.getlist("telegram_user_id")
    results = []
    for uid_str in selected:
        try:
            uid = int(uid_str)
        except ValueError:
            continue
        row = conn.execute("SELECT email FROM students WHERE telegram_user_id=?", (uid,)).fetchone()
        if not row or not row[0]:
            results.append((uid, "skipped"))
            continue
        email = row[0]
        try:
            data_for_name = student_analytics.fetch_student_report_data(conn, uid)
            display_name = generate_student_report.display_name_for_student(data_for_name)
            pdf_bytes = generate_student_report.build_report_pdf(conn, uid)
            report_delivery.send_report_email(BOT_ID, email, pdf_bytes, display_name, "All-time")
            report_delivery.log_report_delivery(conn, uid, "All-time (admin-sent)", "email", email_status="sent")
            results.append((uid, "sent"))
        except Exception as e:
            report_delivery.log_report_delivery(conn, uid, "All-time (admin-sent)", "email",
                                                  email_status="failed", error_detail=str(e))
            results.append((uid, "failed"))

    sent = sum(1 for _, s in results if s == "sent")
    failed = sum(1 for _, s in results if s == "failed")
    skipped = sum(1 for _, s in results if s == "skipped")
    flash(f"Reports: {sent} sent, {failed} failed, {skipped} skipped (no confirmed email on file).",
          "success" if failed == 0 else "error")
    audit.log_action(conn, auth.current_user(), "bulk_report_send", f"{len(selected)} students",
                      f"sent={sent} failed={failed} skipped={skipped}")
    return redirect(url_for("analytics_students"))


