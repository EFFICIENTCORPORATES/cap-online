def _heartbeat_loop(interval_seconds: int = 120):
    """Same technique as dashboard_server.py's own _heartbeat_loop() -- this
    is a plain Flask/WSGI process, no python-telegram-bot Application/
    JobQueue to hang a periodic heartbeat off of, so a daemon background
    thread does the same job. Without this, manage_bots.py status/the
    watcher/the dashboard would never see this process as online."""
    conn = platform_db.get_connection()
    platform_db.init_schema(conn)
    pid = os.getpid()
    started_at = platform_db.now()
    while True:
        platform_db.send_heartbeat(conn, BOT_ID, pid, started_at)
        time.sleep(interval_seconds)


def main():
    threading.Thread(target=_heartbeat_loop, daemon=True).start()
    port = int(os.environ.get("ADMIN_PORTAL_PORT", "8788"))
    app.logger.info(f"1LAVYA Admin Portal starting on http://127.0.0.1:{port}/")
    app.run(host="127.0.0.1", port=port, debug=False, threaded=True)


if __name__ == "__main__":
    main()
