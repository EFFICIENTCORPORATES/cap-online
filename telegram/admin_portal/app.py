COURSE_CATALOG_FILTER_FIELDS = ["chapter_no", "chapter_name", "chapter_name_short", "unit_no", "unit_name"]


def _format_paper_no(paper_no: str) -> str:
    """'1' -> 'P01', '7A' -> 'P7A' -- same rule as generate_mcq_human_ids.py's
    own _format_paper(), duplicated (not imported, telegram/tools/ isn't
    normally on this app's import path) since both are simple/stable enough
    not to need a shared module for one formatting rule."""
    return f"P{str(paper_no).zfill(2)}"


def _course_catalog_course_levels(conn) -> dict:
    """{course: [levels...]} actually present in course_catalog, in a
    stable Foundation->Inter->Final-ish order (by level_num)."""
    rows = conn.execute(
        "SELECT DISTINCT course, level, level_num FROM course_catalog ORDER BY course, level_num"
    ).fetchall()
    out = {}
    for course, level, _ in rows:
        out.setdefault(course, []).append(level)
    return out


