def get_all_table_names(conn) -> list:
    rows = conn.execute(
        "SELECT name FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%' ORDER BY name"
    ).fetchall()
    return [r[0] for r in rows]


@app.route("/export")
@auth.role_required("admin")
def data_export_index():
    conn = get_conn()
    tables = []
    for name in get_all_table_names(conn):
        # name comes only from sqlite_master's own enumeration above, never
        # from request input -- safe to interpolate into SQL as a quoted
        # identifier (Python's DB-API has no separate placeholder syntax
        # for identifiers, only values).
        count = conn.execute(f'SELECT COUNT(*) FROM "{name}"').fetchone()[0]
        tables.append({"name": name, "row_count": count})
    return render_template("data_export.html", tables=tables)


@app.route("/export/<table_name>.<fmt>")
@auth.role_required("admin")
def export_table(table_name, fmt):
    conn = get_conn()
    if table_name not in set(get_all_table_names(conn)):
        return "Unknown table.", 404
    if fmt not in ("json", "csv", "xlsx"):
        return "Unsupported format -- use .json, .csv, or .xlsx", 400

    cursor = conn.execute(f'SELECT * FROM "{table_name}"')
    columns, rows = exporters.rows_from_cursor(cursor)
    audit.log_action(conn, auth.current_user(), "table_export", table_name, fmt)

    if fmt == "json":
        return exporters.json_response(columns, rows, table_name)
    if fmt == "csv":
        return exporters.csv_response(columns, rows, table_name)
    return exporters.xlsx_response(columns, rows, table_name)


