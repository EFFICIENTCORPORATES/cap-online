@app.template_global()
def page_url(page: int) -> str:
    """Used by templates/_pagination.html on every paginated view --
    preserves every OTHER current query arg (filter text, bot_id, etc.),
    only replacing `page`. One implementation, reused everywhere, so a
    paginated page's Next/Prev links never drop a filter a user just
    applied."""
    args = request.args.to_dict(flat=True)
    args["page"] = page
    return f"{request.path}?{urlencode(args)}"


@app.template_global()
def clear_filter_url() -> str:
    """Used by templates/_export_toolbar.html's "Clear" link -- drops `q`
    and `page` but preserves everything else (e.g. Faculty Report's
    bot_id selection), so clearing the text filter doesn't also lose an
    unrelated selection."""
    args = request.args.to_dict(flat=True)
    args.pop("q", None)
    args.pop("page", None)
    return f"{request.path}?{urlencode(args)}" if args else request.path


