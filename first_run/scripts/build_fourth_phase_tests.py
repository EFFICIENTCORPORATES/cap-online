"""
build_fourth_phase_tests.py
===========================
Fourth-phase chapter tests: Financial Statements, Cash Flow, Intro to AS, Applicability, AS 1, AS 17. Same selection
logic, sources and honesty rules as build_second_phase_tests.py (imported and
re-pointed, not copied) - real MTP/RTP/PYQ content first, ICAI Test Your
Knowledge only as a top-up, nothing invented, short tests accepted as short.

Output (first_run/TESTS/fourth phase/):
  <AS>_Questions.md, <AS>_Questions_and_Answers.md, README.md   - for self
  student-edition/<AS>_Questions.pdf, <AS>_Answers.pdf          - student-facing
"""
import json
import sys
from datetime import date
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
import build_second_phase_tests as p2
import extract_study_material_tyk as tyk
import convert_tests_to_pdf as pdfconv

REPO = Path(r"D:\EffCorp_Projects\cap-online")
RAW = REPO / "books" / "ca-inter" / "concept-book" / "raw_icai_study_materials"
OUT = REPO / "first_run" / "TESTS" / "fourth phase"
STUDENT = OUT / "student-edition"
TYK_JSON = REPO / "first_run" / "output" / "generated-from-script" / "study_material_tyk_phase4.json"

CHAPTERS = {
    "financial-statements": ("M3_C11_U1_ Preparation of Financial Statements.md", "M3-C11-U1",
                             "Financial Statements of Companies"),
    "cash-flow-statement": ("M3_C11_U2_ Cash Flow Statement.md", "M3-C11-U2", "Cash Flow Statement (AS 3)"),
    "intro-to-as": ("M1_C1_U1_ Introduction to Accounting Standards.md", "M1-C1-U0", "Introduction to Accounting Standards"),
    "applicability": ("M1_C3_U1_ Applicability of Accounting Standards.md", "M1-C3-U0", "Applicability of Accounting Standards"),
    "as01": ("M1_C4_U1_ Accounting Standard 1 Disclosure of Accounting Policies.md", "M1-C4-U1", "AS 1 — Disclosure of Accounting Policies"),
    "as17": ("M1_C4_U3_ Accounting Standard 17 Segment Reporting.md", "M1-C4-U3", "AS 17 — Segment Reporting"),
}

# --- re-point phase-2 module ---
tyk.SRC_DIR = RAW
tyk.OUT_PATH = TYK_JSON
tyk.CHAPTERS = CHAPTERS
p2.STUDY_TYK_PATH = TYK_JSON
p2.AS_LIST = list(CHAPTERS)
p2.CHAPTER_MAP = {k: v[1] for k, v in CHAPTERS.items()}
p2.AS_NAME = {k: v[2] for k, v in CHAPTERS.items()}


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    STUDENT.mkdir(parents=True, exist_ok=True)
    tyk.main()
    mcq_pool = p2.load_json(p2.MCQ_PATH)
    desc_pool = p2.load_json(p2.DESC_PATH)
    tests = []
    for k in CHAPTERS:
        t = p2.build_test(k, mcq_pool, desc_pool)
        tests.append(t)
        if t["achieved_total"] == 0:
            print(f"{k.upper():10} EMPTY pool - no test files written")
            continue
        q_md = p2.render_questions_md(t)
        qa_md = p2.render_answers_md(t)
        (OUT / f"{k.upper()}_Questions.md").write_text(q_md, encoding="utf-8")
        (OUT / f"{k.upper()}_Questions_and_Answers.md").write_text(qa_md, encoding="utf-8")
        # answers-only student file: header + the "## Answers" block
        head = "\n".join(p2.render_header(t))
        ans_part = qa_md[qa_md.index("## Answers"):]
        a_md = f"{head}\n## Answer Key\n\n" + ans_part[len("## Answers"):]
        tmp_dir = OUT / "_tmp"
        tmp_dir.mkdir(exist_ok=True)
        (tmp_dir / f"{k.upper()}_Questions.md").write_text(q_md, encoding="utf-8")
        (tmp_dir / f"{k.upper()}_Answers.md").write_text(a_md, encoding="utf-8")
        print(f"{k.upper():10} {t['achieved_total']}/50  MCQ {t['mcq_marks']} ({t['mcq_count']}q)  "
              f"DESC {t['desc_marks']} ({t['desc_count']}q)  pool max {t['max_total_available']}  study={t['used_study_material']}")
    pdfconv.convert_all(OUT / "_tmp", STUDENT)
    for f in (OUT / "_tmp").glob("*.md"):
        f.unlink()
    try:
        (OUT / "_tmp").rmdir()
    except OSError:
        pass  # desktop.ini keeps the empty folder locked on this machine

    L = ["# Fourth Phase — Chapter Tests (MCQ + Descriptive, up to 50 Marks)", "",
         "Financial Statements of Companies, Cash Flow Statement, Introduction to AS, Applicability of AS, AS 1 and AS 17. Same method and sources as "
         "Phase 2 (`build_second_phase_tests.py`): real MTP/RTP/PYQ questions first (official marks), ICAI "
         "\"Test Your Knowledge\" only as a top-up (marks estimated, tagged). Nothing invented; short tests are "
         "accepted as short. Generated by `first_run/scripts/build_fourth_phase_tests.py`.", "",
         "`*.md` here are for self. `student-edition/` holds the watermarked PDFs: Questions and Answers separately.", "",
         "| Chapter | Marks | MCQ | Descriptive | Study material | Status |", "|---|---|---|---|---|---|"]
    for t in tests:
        st = "**NO TEST — no questions tagged to this chapter and no usable study-material answers**" if t["achieved_total"] == 0 else "OK — full 50" if t["achieved_total"] >= 50 else f"**SHORT — {t['achieved_total']}/50** (pool max {t['max_total_available']})"
        L.append(f"| {t['name']} | {t['achieved_total']}/50 | {t['mcq_marks']} ({t['mcq_count']}q) | "
                 f"{t['desc_marks']} ({t['desc_count']}q) | {'Yes' if t['used_study_material'] else 'No'} | {st} |")
    L += ["", f"*Generated: {date.today().isoformat()}*", ""]
    (OUT / "README.md").write_text("\n".join(L), encoding="utf-8")


if __name__ == "__main__":
    main()
