# Front-to-back order of the finished book, expressed as plain slugs (same
# pattern as strategy_book_merge.py's BOOK_ORDER) -- "front-matter" and
# "back-matter" are special-cased in build_merged_html() below, everything
# else is looked up in CHAPTERS.
BOOK_ORDER = ("front-matter",) + tuple(c[0] for c in CHAPTERS) + ("back-matter",)

FRONT_MATTER_FILE = "front-matter.html"
BACK_MATTER_FILE = "back-matter.html"

_SLUG_TO_CHAPTER = {
    slug: (filename, label, study_ref) for slug, filename, label, study_ref in CHAPTERS
}

MERGE_ONLY_CSS = """
/* ── Added only for the merged whole-book file (qb_merge.py) ──
   Belt-and-braces: .qb-section already carries break-before:page from
   qb_common.print_layer_css(), this just documents that the merge is what
   makes the rule meaningful (a lone file has nothing to break away from). */
"""


def validate_order(order: tuple, output_dir: Path, output_name: str, force: bool) -> None:
    """Cross-check BOOK_ORDER against what's actually in output/ -- same
    two-directional check as strategy_book_merge.py's validate_order()."""
    missing = []
    for slug in order:
        if slug == "front-matter":
            candidates = [output_dir / FRONT_MATTER_FILE]
        elif slug == "back-matter":
            candidates = [output_dir / BACK_MATTER_FILE]
        else:
            filename, _label, _ref = _SLUG_TO_CHAPTER[slug]
            candidates = [output_dir / filename, qc.CHAPTERS_DIR / filename]
        if not any(c.exists() for c in candidates):
            missing.append(f"{slug} -> {candidates[-1].name} (checked: "
                            + ", ".join(str(c.parent) for c in candidates) + ")")
    if missing:
        raise SystemExit(
            "ERROR: BOOK_ORDER lists section(s) with no file on disk:\n  "
            + "\n  ".join(missing)
        )

    # Only *_Question_Book.html files are candidate chapters -- the sitting-
    # level Layer 1 files (MTP_*.html, PYQ_*.html, RTP_*.html) also live
    # nearby but are raw per-sitting source, never merged into the book
    # directly (see CLAUDE.md section 6's pipeline description). Checked in
    # BOTH output/ and output/generated-from-script/ -- see qb_common.py's
    # CHAPTERS_DIR comment for why the chapter files' location isn't fixed.
    chapter_filenames = {c[1] for c in CHAPTERS}
    all_book_files = {p.name for p in output_dir.glob("*_Question_Book.html")}
    if qc.CHAPTERS_DIR.is_dir():
        all_book_files |= {p.name for p in qc.CHAPTERS_DIR.glob("*_Question_Book.html")}
    orphaned = sorted(all_book_files - chapter_filenames)
    if orphaned:
        msg = (
            "*_Question_Book.html-shaped file(s) exist in output/ but "
            "aren't listed in CHAPTERS (they will be silently left out of "
            "the merged book):\n  " + "\n  ".join(orphaned)
        )
        if force:
            print(f"WARNING: {msg}\n(--force: proceeding anyway)")
        else:
            raise SystemExit(
                f"ERROR: {msg}\n"
                "Add them to CHAPTERS in this script, or re-run with "
                "--force if leaving them out is intentional."
            )


def check_vendor_present(output_dir: Path) -> None:
    """Same sanity check as strategy_book_merge.py's check_vendor_present()
    -- the merged file references vendor/ with a plain relative path since
    it lives in the same folder vendor/ is already in (see module
    docstring point 4)."""
    polyfill = output_dir / "vendor" / "paged.polyfill.js"
    fonts_css = output_dir / "vendor" / "gfonts-local.css"
    missing = [p for p in (polyfill, fonts_css) if not p.exists()]
    if missing:
        raise SystemExit(
            "ERROR: missing vendor file(s), the merged book would silently "
            "fail to paginate/render fonts:\n  "
            + "\n  ".join(str(p) for p in missing)
        )


def build_merged_html(output_dir: Path, order: tuple, style: dict) -> str:
    shared_chapter_style = qc.verify_shared_style([c[1] for c in CHAPTERS])
    # Fonts are INLINED (not <link>ed) here -- confirmed by direct testing
    # (2026-07-26) that paged.js internally re-fetches every <link
    # rel="stylesheet"> via XHR to analyze its rules, and Chrome blocks that
    # XHR under file:// origin (CORS): "Access to XMLHttpRequest ... has
    # been blocked by CORS policy". The failure is silent to a casual look
    # -- an uncaught promise rejection, zero console error dialog, paged.js
    # simply never starts (.pagedjs_page count stayed at 0 for 115+ seconds
    # of real-time polling before this was traced). Inlining the same CSS
    # text directly into the <style> block sidesteps the extra fetch
    # entirely -- the woff2 files themselves still load fine via ordinary
    # @font-face resource loading, which file:// does allow.
    fonts_css = (output_dir / "vendor" / "gfonts-local.css").read_text(encoding="utf-8")
    # gfonts-local.css's url(fonts/font-NNN.woff2) paths are relative to
    # ITS OWN location (vendor/gfonts-local.css), i.e. really
    # vendor/fonts/font-NNN.woff2. Once inlined into a <style> block that
    # lives in the merged document's own <head>, relative url()s resolve
    # against the DOCUMENT's location instead -- so the "fonts/" prefix
    # must be rewritten to "vendor/fonts/" or every font 404s silently.
    fonts_css = fonts_css.replace("url(fonts/", "url(vendor/fonts/")
    full_style = (
        fonts_css
        + shared_chapter_style
        + qc.print_layer_css(style)
        + qc.front_back_css(style)
        + MERGE_ONLY_CSS
    )

    sections_html = []
    for slug in order:
        if slug == "front-matter":
            html_text = qc.load_chapter_html(FRONT_MATTER_FILE)
            sections_html.append(qc.extract_body_inner(html_text))
        elif slug == "back-matter":
            html_text = qc.load_chapter_html(BACK_MATTER_FILE)
            sections_html.append(qc.extract_body_inner(html_text))
        else:
            filename, label, study_ref = _SLUG_TO_CHAPTER[slug]
            html_text = qc.load_chapter_html(filename)
            sections_html.append(qc.page_shell(html_text, slug, label, study_ref))

    body = "\n\n".join(sections_html)

    return f"""<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="UTF-8">
  <meta name="viewport" content="width=device-width, initial-scale=1.0">
  <title>{qc.BOOK_TITLE}</title>
  <style>{full_style}</style>
</head>
<body>
{body}
<script src="vendor/paged.polyfill.js"></script>
</body>
</html>"""


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument(
        "--output", default="QUESTION-BANK-BOOK.html",
        help="Output filename, written INTO first_run/output/ (must stay "
             "there so the vendor/... references keep working)."
    )
    ap.add_argument(
        "--force", action="store_true",
        help="Proceed past an orphaned-file warning instead of stopping."
    )
    args = ap.parse_args()

    output_dir = qc.OUTPUT_DIR
    style = qc.load_book_style()

    validate_order(BOOK_ORDER, output_dir, args.output, args.force)
    check_vendor_present(output_dir)

    merged = build_merged_html(output_dir, BOOK_ORDER, style)

    out_path = output_dir / args.output
    out_path.write_text(merged, encoding="utf-8")

    print(f"Merged {len(BOOK_ORDER)} sections -> {out_path}")
    print(f"  ({len(merged):,} characters)")
    print(
        "Next: open this file in Chrome, wait for paged.js to finish "
        "paginating (a 34-chapter book takes noticeably longer than any "
        "single section -- that's expected), then Ctrl+P -> Save as PDF "
        "with Background graphics enabled."
    )


if __name__ == "__main__":
    main()
