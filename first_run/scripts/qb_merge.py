#!/usr/bin/env python3
"""
qb_merge.py: Question Bank Book: whole-book assembler
=========================================================

Same job as tools/strategy_book_merge.py, done for the Question Bank Book:
stitch independent, already-finished files (34 per-chapter files whose
"main content is done" per Pranav, plus front-matter.html and
back-matter.html) into ONE continuous HTML document so paged.js can
paginate the whole book as a single flow -- the only way to get continuous
page numbers and a running header that's correct on every physical page.

Read the strategy book's merge script docstring first if you haven't --
this file reuses every lesson from it (duplicate-style detection, id
collisions, page-break-per-section, vendor-path safety, an explicit
human-edited BOOK_ORDER cross-checked against what's actually on disk).
Only what's genuinely different about the Question Bank Book is explained
below.

WHAT'S DIFFERENT FROM THE STRATEGY BOOK MERGE
------------------------------------------------
1. TWO style layers, not one. The 34 chapter files share one embedded
   <style> (verified byte-identical -- qb_common.verify_shared_style).
   front-matter.html and back-matter.html carry a DIFFERENT, richer style
   (title page, copyright page, author bio -- classes the chapters never
   use). Rather than pick one file as "the" reference style (which is what
   the strategy book does, because every one of its files shares the exact
   same style), this script builds the merged <head> additively out of
   three known-safe pieces: the verified chapter style, qb_common's shared
   print/pagination layer, and qb_common's shared front/back-matter layer.
   front-matter.html and back-matter.html contribute only their BODY
   content here -- their own <style> tags are never pulled into the merged
   file, since qb_common.front_back_css() already IS that style, shared
   losslessly with the two generator scripts that use it.

2. The id="AS02-NNN" bug (see qb_common.py's module docstring) is fixed
   here at merge time via qb_common.rewrite_qblock_ids(), applied through
   qb_common.page_shell() for every chapter. front-matter.html and
   back-matter.html don't have this bug (they were never generated by the
   buggy generate_chapter_book.py), so they're inserted as-is.

3. Running header/footer only appear on chapter pages, not front/back
   matter -- ordinary book convention (a title page or copyright page
   doesn't carry a running header). qb_common.page_shell() adds the
   running-header/footer elements; front/back matter content is inserted
   directly without that wrapper.

4. Vendor paths are NOT "../vendor/..." like the strategy book -- this
   script writes its output directly into first_run/output/, the same
   folder vendor/ already lives in (see qb_common.VENDOR_DIR), so a plain
   "vendor/paged.polyfill.js" relative path is correct as-is.

USAGE
-----
    python qb_merge.py
        Merge using BOOK_ORDER below, write
        first_run/output/QUESTION-BANK-BOOK.html

    python qb_merge.py --force
        Proceed past an orphaned-file warning (a file sits in output/ that
        isn't listed in BOOK_ORDER) instead of stopping. Never overrides a
        missing-file error -- there's nothing sensible to substitute for a
        missing chapter.

After running: open the file in Chrome, wait for paged.js to finish
repainting (a 34-chapter book will take noticeably longer than any single
section -- that's expected, not a hang), then Ctrl+P -> Save as PDF with
Background graphics enabled.
"""

