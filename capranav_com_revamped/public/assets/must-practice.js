/* Must Practice Questions — unit picker, question table and answer reveal.
   Each published unit is a static JSON file under ./data/<unit_id>.json,
   generated by capranav_com_revamped/tools/build_must_practice_data.py.
   Units with published:false render a "coming soon" panel instead. */

const DATA_ROOT = "/practice-with-pranav-bhaiya/must-practice/data";
let CATALOGUE = [];
let DEFAULT_UNIT = null;

const moduleSelect = document.getElementById("module-select");
const chapterSelect = document.getElementById("chapter-select");
const unitSelect = document.getElementById("unit-select");
const unitPanel = document.getElementById("unit-panel");
const soonPanel = document.getElementById("soon-panel");
const qBody = document.getElementById("q-body");

const cache = new Map();

function option(value, label, disabled) {
  const el = document.createElement("option");
  el.value = value;
  el.textContent = label;
  if (disabled) el.disabled = true;
  return el;
}

function currentModule() {
  return CATALOGUE.find((m) => m.module === moduleSelect.value);
}

function currentChapter() {
  const mod = currentModule();
  return mod && mod.chapters.find((c) => c.chapter === chapterSelect.value);
}

function currentUnit() {
  const chapter = currentChapter();
  return chapter && chapter.units.find((u) => u.unit_id === unitSelect.value);
}

function fillModules() {
  moduleSelect.replaceChildren(...CATALOGUE.map((m) => option(m.module, m.module)));
  const home = locate(DEFAULT_UNIT);
  if (home) moduleSelect.value = home.module.module;
  fillChapters(home);
}

/* Find the module/chapter a unit_id sits in, so the page opens on the
   published unit rather than on whatever happens to sort first. */
function locate(unitId) {
  for (const module of CATALOGUE) {
    for (const chapter of module.chapters) {
      if (chapter.units.some((u) => u.unit_id === unitId)) return { module, chapter };
    }
  }
  return null;
}

function fillChapters(home) {
  const mod = currentModule();
  chapterSelect.replaceChildren(...mod.chapters.map((c) => option(c.chapter, c.chapter)));
  if (home && home.module === mod) chapterSelect.value = home.chapter.chapter;
  fillUnits(home);
}

function fillUnits(home) {
  const chapter = currentChapter();
  unitSelect.replaceChildren(
    ...chapter.units.map((u) => option(u.unit_id, u.published ? u.label : `${u.label} — coming soon`))
  );
  if (home && home.chapter === chapter) unitSelect.value = DEFAULT_UNIT;
  loadUnit();
}

function escapeHtml(text) {
  return String(text).replace(/[&<>"]/g, (ch) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" }[ch]));
}

function marksLabel(question) {
  const raw = (question.marks_text || "").replace(/^Marks:\s*/, "").trim();
  return !raw || /not stated/i.test(raw) ? "&mdash;" : escapeHtml(raw);
}

function topicTags(question) {
  const tags = question.topics.map((topic) => {
    const band = topic.priority_band === "Top 50" ? "top50" : topic.priority_band === "Next 50" ? "next50" : "";
    return `<span class="tag ${band}">Rank ${topic.overall_rank} &middot; ${escapeHtml(topic.topic_name)}</span>`;
  });
  if (question.study_match_category === "A" || question.study_match_category === "B") {
    const pct = question.study_match_percent ? `${Math.round(question.study_match_percent)}%` : "";
    tags.push(`<span class="tag match">Study Material match ${pct}</span>`);
  }
  question.badges.forEach((badge) => tags.push(`<span class="tag">${escapeHtml(badge)}</span>`));
  return tags.join("");
}

function shortTopic(question) {
  return (question.topic_text || "").replace(/^Topic\s+[\d./]+:\s*/, "");
}

function renderQuestions(data) {
  qBody.replaceChildren();

  data.questions.forEach((question) => {
    const row = document.createElement("tr");
    row.className = "q-row";
    row.tabIndex = 0;
    row.innerHTML = `
      <td class="col-no"><span class="rank">${question.position}</span></td>
      <td>
        <div class="q-title">${escapeHtml(data.standard)} &middot; ${escapeHtml(question.question_no)}</div>
        <div class="q-topic">${escapeHtml(shortTopic(question))}</div>
        <div class="q-tags">${topicTags(question)}</div>
      </td>
      <td class="col-src paper">${escapeHtml(question.paper_type)}<small>${escapeHtml(question.source_label)}</small></td>
      <td class="col-marks">${marksLabel(question)}</td>
      <td class="col-page pg">${question.book_page ? "p. " + question.book_page : "&mdash;"}<small>${question.book_page ? "Question Bank" : "not traced"}</small></td>`;

    const detailRow = document.createElement("tr");
    detailRow.hidden = true;
    detailRow.innerHTML = `<td class="detail-row-cell" colspan="5"></td>`;
    detailRow.className = "detail-row";

    const noteClass = question.mistake_type === "icai" ? "icai" : "synth";
    const noteTitle = question.mistake_type === "icai" ? "ICAI Examiner&rsquo;s Comment" : "Author&rsquo;s Note";
    const noteText = (question.mistake_text || "").replace(/^(Author’s Note|Examiner’s Comment):\s*/, "");

    detailRow.firstElementChild.innerHTML = `
      <div class="detail">
        <h3>Why this one</h3>
        <p class="why">${escapeHtml(question.why)}</p>
        <h3>Question</h3>
        <div class="qtext">${question.question_html}</div>
        <button class="show-answer" type="button">Show answer</button>
        <div class="answer" hidden>
          <h3>Answer</h3>
          <div class="atext">${question.answer_html}</div>
          ${noteText ? `<div class="note ${noteClass}"><strong>${noteTitle}</strong>${escapeHtml(noteText)}</div>` : ""}
        </div>
      </div>`;

    const toggle = () => {
      detailRow.hidden = !detailRow.hidden;
    };
    row.addEventListener("click", toggle);
    row.addEventListener("keydown", (event) => {
      if (event.key === "Enter" || event.key === " ") {
        event.preventDefault();
        toggle();
      }
    });

    const button = detailRow.querySelector(".show-answer");
    const answer = detailRow.querySelector(".answer");
    button.addEventListener("click", () => {
      answer.hidden = !answer.hidden;
      button.textContent = answer.hidden ? "Show answer" : "Hide answer";
    });

    qBody.append(row, detailRow);
  });
}

function renderUnit(data) {
  document.getElementById("unit-title").textContent = `${data.standard} — ${data.unit_title}`;
  document.getElementById("unit-sub").textContent =
    `${data.module} · ${data.chapter} · shortlisted from ${data.library_total} descriptive questions across every MTP, RTP and PYQ from 2023 onwards.`;
  document.getElementById("unit-count").textContent = data.questions.length;
  document.getElementById("book-note").textContent =
    `Page numbers refer to ${data.book_edition}. Every question and answer here is reproduced from that book.`;
  renderQuestions(data);
  unitPanel.hidden = false;
  soonPanel.hidden = true;
}

async function loadUnit() {
  const unit = currentUnit();
  if (!unit || !unit.published) {
    unitPanel.hidden = true;
    soonPanel.hidden = false;
    return;
  }
  if (cache.has(unit.unit_id)) {
    renderUnit(cache.get(unit.unit_id));
    return;
  }
  try {
    const response = await fetch(`${DATA_ROOT}/${unit.unit_id}.json`);
    if (!response.ok) throw new Error(response.status);
    const data = await response.json();
    cache.set(unit.unit_id, data);
    renderUnit(data);
  } catch (error) {
    unitPanel.hidden = true;
    soonPanel.hidden = false;
  }
}

moduleSelect.addEventListener("change", () => fillChapters());
chapterSelect.addEventListener("change", () => fillUnits());
unitSelect.addEventListener("change", loadUnit);

(async function init() {
  try {
    const response = await fetch(`${DATA_ROOT}/index.json`);
    if (!response.ok) throw new Error(response.status);
    const index = await response.json();
    CATALOGUE = index.modules;
    DEFAULT_UNIT = index.default_unit;
    fillModules();
  } catch (error) {
    unitPanel.hidden = true;
    soonPanel.hidden = false;
  }
})();
